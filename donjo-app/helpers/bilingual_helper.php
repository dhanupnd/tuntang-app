if (! function_exists('bilingual_day')) {
    function bilingual_day($day)
    {
        $days = [
            'Minggu' => 'day_sunday',
            'Senin'  => 'day_monday',
            'Selasa' => 'day_tuesday',
            'Rabu'   => 'day_wednesday',
            'Kamis'  => 'day_thursday',
            'Jumat'  => 'day_friday',
            'Sabtu'  => 'day_saturday',
        ];

        return bilingual_text($days[$day] ?? $day);
    }
}

if (! function_exists('bilingual_switch_url')) {
    function bilingual_switch_url($language)
    {
        $queryString = $_SERVER['QUERY_STRING'] ?? '';
        $currentUrl = current_url() . ($queryString ? '?' . $queryString : '');

        return site_url('bahasa/' . $language) . '?redirect=' . rawurlencode($currentUrl);
    }
